/**
 * Episodic memory: short text entries, no embeddings. Retrieval is a weighted
 * sum of recency, importance and cheap lexical relevance (see docs/AI_DESIGN.md).
 */

import type { MemoryId } from '../core/index';
import { clamp01 } from '../core/index';
import type { ActorId } from './relationships';

export interface MemoryEntry {
  id: MemoryId;
  /** In-game simulation tick when the event happened. */
  tick: number;
  /** Wall-clock timestamp, used for recency decay. */
  timestampMs: number;
  participants: readonly ActorId[];
  locationTag: string;
  /** One short sentence in Slovak, as generated by the LLM. */
  text: string;
  /** Dominant emotion at the time. */
  emotion: string;
  /** 1 (trivia) .. 10 (formative). */
  importance: number;
  keywords: readonly string[];
}

export interface MemoryRetrievalContext {
  nowMs: number;
  participants: readonly ActorId[];
  tags: readonly string[];
  keywords: readonly string[];
}

export const MEMORY_RETRIEVAL_WEIGHTS = {
  recency: 0.45,
  importance: 0.3,
  relevance: 0.25,
} as const;

/** Entries above this count are candidates for compaction. */
export const MEMORY_COMPACTION_THRESHOLD = 40;
/** How many entries survive rule-based truncation. */
export const MEMORY_KEEP_AFTER_TRUNCATION = 15;
/** Retrieval top-K inserted into prompts. */
export const MEMORY_TOP_K = 5;

const RECENCY_HALF_LIFE_HOURS = 72;

function overlap(a: readonly string[], b: readonly string[]): number {
  if (a.length === 0 || b.length === 0) return 0;
  const left = new Set(a.map((value) => value.toLowerCase()));
  const right = new Set(b.map((value) => value.toLowerCase()));
  let shared = 0;
  for (const value of left) if (right.has(value)) shared += 1;
  return shared / Math.max(left.size, right.size);
}

export function memoryRetrievalScore(entry: MemoryEntry, context: MemoryRetrievalContext): number {
  const ageHours = Math.max(0, context.nowMs - entry.timestampMs) / 3_600_000;
  const recency = Math.exp(-ageHours / RECENCY_HALF_LIFE_HOURS);
  const importance = clamp01(entry.importance / 10);
  const participantMatch = entry.participants.some((id) => context.participants.includes(id))
    ? 1
    : 0;
  const tagMatch = overlap(entry.keywords, context.tags);
  const keywordMatch = overlap(entry.keywords, context.keywords);
  const relevance = 0.5 * participantMatch + 0.3 * tagMatch + 0.2 * keywordMatch;

  return (
    MEMORY_RETRIEVAL_WEIGHTS.recency * recency +
    MEMORY_RETRIEVAL_WEIGHTS.importance * importance +
    MEMORY_RETRIEVAL_WEIGHTS.relevance * relevance
  );
}
